#!/usr/bin/env python3
"""Convert 16 kHz mono 16-bit WAV clips into a single LVGL-agnostic C table."""

from pathlib import Path
import argparse
import wave


CLIPS = (("five_seconds", "five.wav"), ("time_up", "done.wav"))


def pcm_payload(path: Path) -> bytes:
    with wave.open(str(path), "rb") as source:
        if source.getnchannels() != 1 or source.getsampwidth() != 2 or source.getframerate() != 16000:
            raise ValueError(f"{path}: expected 16 kHz mono signed 16-bit")
        return source.readframes(source.getnframes())


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("assets", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    args.output.parent.mkdir(parents=True, exist_ok=True)

    body = []
    for symbol, filename in CLIPS:
        data = pcm_payload(args.assets / filename)
        body.append(f"const uint8_t voice_{symbol}[] = {{")
        for offset in range(0, len(data), 16):
            row = ", ".join(f"0x{byte:02x}" for byte in data[offset:offset + 16])
            body.append(f"    {row},")
        body.append("};")
        body.append(f"const uint32_t voice_{symbol}_len = sizeof(voice_{symbol});")
        body.append("")

    args.output.write_text("/* Generated by tools/generate_voice.py. 16 kHz mono PCM. */\n"
                           "#include <stdint.h>\n\n" + "\n".join(body))


if __name__ == "__main__":
    main()
